      <a href="<?= BASE_URL ?>/supervisor/dashboard.php">Overview</a>
      <a href="<?= BASE_URL ?>/supervisor/all_requests.php">View All Requests</a>
      <a class="active" href="<?= BASE_URL ?>/supervisor/reports.php">Generate Reports</a>
    </nav>
  </aside>
  <main class="requester-main">
    <div class="page-header">
      <div><h1>Reports &amp; Analytics</h1><div class="subtitle">Generated by month, building, category, technician, and status (FR-14, FR-15).</div></div>
    </div>
      <div class="stat-grid">
        <div class="stat-card"><div class="stat-value"><?= (int) $overall['total'] ?></div><div class="stat-label">Total Requests</div></div>
        <div class="stat-card gold"><div class="stat-value"><?= (int) $overall['open_requests'] ?></div><div class="stat-label">Open Requests</div></div>
        <div class="stat-card"><div class="stat-value"><?= (int) $overall['completed'] ?></div><div class="stat-label">Completed Requests</div></div>
        <div class="stat-card"><div class="stat-value"><?= (int) $overall['rejected'] ?></div><div class="stat-label">Rejected Requests</div></div>
        <div class="stat-card"><div class="stat-value"><?= $overall['avg_hours'] ? number_format($overall['avg_hours'], 1) . 'h' : '—' ?></div><div class="stat-label">Avg. Resolution Time</div></div>
      </div>

      <div class="card">
        <h2 class="mt-0">Requests by Status</h2>
        <div class="report-chart" role="img" aria-label="Requests by status bar graph">
        <?php foreach ($byStatus as $s): ?>
          <div class="report-bar-row">
            <div class="report-bar-label"><span class="badge <?= status_badge_class($s['status']) ?>"><?= e($s['status']) ?></span></div>
            <div class="report-bar-track"><div class="report-bar-fill" style="width:<?= max(4, round($s['total'] / $maxStatusTotal * 100)) ?>%;"></div></div>
            <strong class="report-bar-value"><?= (int) $s['total'] ?></strong>
          </div>
        <?php endforeach; ?>
        </div>
      </div>

      <div class="report-chart-grid">
        <div class="card">
          <h2 class="mt-0">Requests by Month</h2>
          <div class="vertical-chart" role="img" aria-label="Requests by month bar graph">
            <?php $maxMonthTotal = max(array_column($byMonth, 'total') ?: [1]); foreach (array_reverse($byMonth) as $row): ?>
              <div class="vertical-bar-column"><div class="vertical-bar" style="height:<?= max(5, round($row['total'] / $maxMonthTotal * 100)) ?>%;" title="<?= e($row['period']) ?>: <?= (int) $row['total'] ?>"></div><span><?= e(substr($row['period'], 5)) ?></span></div>
            <?php endforeach; ?>
          </div>
        </div>
        <div class="card">
          <h2 class="mt-0">Requests by Category</h2>
          <div class="report-chart" role="img" aria-label="Requests by category bar graph">
            <?php $maxCategoryTotal = max(array_column($byCategory, 'total') ?: [1]); foreach ($byCategory as $row): ?>
              <div class="report-bar-row"><div class="report-bar-label report-text-label"><?= e($row['category_name']) ?></div><div class="report-bar-track"><div class="report-bar-fill category" style="width:<?= max(4, round($row['total'] / $maxCategoryTotal * 100)) ?>%;"></div></div><strong class="report-bar-value"><?= (int) $row['total'] ?></strong></div>
            <?php endforeach; ?>
          </div>
        </div>
      </div>

      <div class="card">
        <h2 class="mt-0">By Month</h2>
        <div class="table-wrap">
          <table class="data-table">
            <thead><tr><th>Month</th><th>Total</th><th>Completed</th></tr></thead>
            <tbody><?php foreach ($byMonth as $row): ?><tr><td><?= e($row['period']) ?></td><td><?= (int) $row['total'] ?></td><td><?= (int) $row['completed'] ?></td></tr><?php endforeach; ?></tbody>
          </table>
        </div>
      </div>

      <div class="card">
        <h2 class="mt-0">By Building</h2>
        <div class="table-wrap">
          <table class="data-table">
            <thead><tr><th>Building</th><th>Total</th><th>Completed</th></tr></thead>
            <tbody><?php foreach ($byBuilding as $row): ?><tr><td><?= e($row['building_name']) ?></td><td><?= (int) $row['total'] ?></td><td><?= (int) $row['completed'] ?></td></tr><?php endforeach; ?></tbody>
          </table>
        </div>
      </div>

      <div class="card">
        <h2 class="mt-0">By Category</h2>
        <div class="table-wrap">
          <table class="data-table">
            <thead><tr><th>Category</th><th>Total</th><th>Completed</th></tr></thead>
            <tbody><?php foreach ($byCategory as $row): ?><tr><td><?= e($row['category_name']) ?></td><td><?= (int) $row['total'] ?></td><td><?= (int) $row['completed'] ?></td></tr><?php endforeach; ?></tbody>
          </table>
        </div>
      </div>

      <div class="card">
        <h2 class="mt-0">By Technician</h2>
        <div class="table-wrap">
          <table class="data-table">
            <thead><tr><th>Technician</th><th>Total Assigned</th><th>Completed</th><th>Avg. Resolution</th></tr></thead>
            <tbody>
              <?php foreach ($byTechnician as $row): ?>
                <tr><td><?= e($row['full_name']) ?></td><td><?= (int) $row['total'] ?></td><td><?= (int) $row['completed'] ?></td><td><?= $row['avg_hours'] ? number_format($row['avg_hours'], 1) . 'h' : '—' ?></td></tr>
              <?php endforeach; ?>
            </tbody>
          </table>
        </div>
      </div>
      <div class="report-downloads report-downloads-bottom" aria-label="Download reports">
        <a class="btn btn-outline-nav btn-sm" href="<?= BASE_URL ?>/supervisor/export_report.php?format=pdf">Download PDF</a>
        <a class="btn btn-outline-nav btn-sm" href="<?= BASE_URL ?>/supervisor/export_report.php?format=word">Download Word</a>
        <a class="btn btn-accent btn-sm" href="<?= BASE_URL ?>/supervisor/export_report.php?format=excel">Download Excel</a>
      </div>
  </div>
