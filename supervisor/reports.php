<?php
require_once __DIR__ . '/../config/config.php';
require_once __DIR__ . '/../includes/functions.php';
require_role([ROLE_SUPERVISOR, ROLE_ADMIN]);

$user = current_user();

// FR-15: dashboard analytics — totals + average resolution time.
$overall = $pdo->query(
    "SELECT COUNT(*) AS total,
            SUM(status = 'Submitted') + SUM(status='Assigned') + SUM(status='Pending') AS open_requests,
            SUM(status = 'Rejected') AS rejected,
            SUM(status = 'Completed') AS completed,
            AVG(CASE WHEN status = 'Completed' THEN TIMESTAMPDIFF(HOUR, submitted_at, completed_at) END) AS avg_hours
     FROM maintenance_requests"
)->fetch();

// FR-14: reports by month, building, category, technician, status.
$byMonth = $pdo->query(
    "SELECT DATE_FORMAT(submitted_at, '%Y-%m') AS period, COUNT(*) AS total,
            SUM(status='Completed') AS completed
     FROM maintenance_requests GROUP BY period ORDER BY period DESC LIMIT 12"
)->fetchAll();

$byBuilding = $pdo->query(
    "SELECT b.building_name, COUNT(*) AS total, SUM(r.status='Completed') AS completed
     FROM maintenance_requests r JOIN buildings b ON b.building_id = r.building_id
     GROUP BY b.building_name ORDER BY total DESC"
)->fetchAll();

$byCategory = $pdo->query(
    "SELECT c.category_name, COUNT(*) AS total, SUM(r.status='Completed') AS completed
     FROM maintenance_requests r JOIN categories c ON c.category_id = r.category_id
     GROUP BY c.category_name ORDER BY total DESC"
)->fetchAll();

$byTechnician = $pdo->query(
    "SELECT u.full_name, COUNT(*) AS total, SUM(r.status='Completed') AS completed,
            AVG(CASE WHEN r.status='Completed' THEN TIMESTAMPDIFF(HOUR, r.submitted_at, r.completed_at) END) AS avg_hours
     FROM assignments a
     JOIN users u ON u.user_id = a.technician_id
     JOIN maintenance_requests r ON r.request_id = a.request_id
     GROUP BY u.full_name ORDER BY total DESC"
)->fetchAll();

$byStatus = $pdo->query(
    "SELECT status, COUNT(*) AS total FROM maintenance_requests GROUP BY status"
)->fetchAll();
$maxStatusTotal = max(array_column($byStatus, 'total') ?: [1]);

$activePage = 'reports';
$pageTitle = 'Reports';
require __DIR__ . '/../includes/header.php';
?>
<div class="requester-dashboard supervisor-dashboard">
  <aside class="requester-rail">
